            '  <div class="th-ring" style="top:0;left:0;width:220px;height:220px"></div>',
            '  <div class="th-ring" style="top:37px;left:37px;width:146px;height:146px"></div>',
            '  <div class="th-ring" style="top:74px;left:74px;width:72px;height:72px"></div>',
            '  <div class="th-sweep"></div>',
            "</div>",
